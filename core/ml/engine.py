LANG_NAMES = {"en": "English", "pcm": "Nigerian Pidgin", "hau": "Hausa", "edo": "Edo"}

def generate_announcement(event_type, lang="en", **fields):
    """Template-and-fill NLP generation. event_type in STRINGS, lang in LANG_NAMES."""
    if event_type not in STRINGS:
        raise ValueError("unknown event type: " + event_type)
    template = STRINGS[event_type].get(lang, STRINGS[event_type]["en"])
    safe = {"flight": "", "gate": "", "dest": "", "newgate": "", "mins": ""}
    safe.update({k: v for k, v in fields.items() if v is not None})
    return template.format(**safe)

def translate(event_type, fields, lang):
    return generate_announcement(event_type, lang=lang, **fields)

