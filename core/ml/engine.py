"""
engine.py
Runtime intelligence used by the web application:
  - load_models(): loads the trained .pkl models once
  - predict_missed_boarding(passenger): risk score + band for one passenger
  - predict_delay(flight): delay probability for one flight
  - generate_announcement(event): NLP template-and-fill announcement text
  - translate(text_key, lang): multilingual rendering (EN, PCM, HAU, EDO)

Announcement text is generated by a controlled template-and-fill method rather
than free generation, so phrasing is always correct and never hallucinated.
Indigenous-language output uses curated verified strings, which is the honest
choice given the immaturity of machine translation for these languages.
"""
import os
import joblib
import pandas as pd

HERE = os.path.dirname(__file__)
MODEL_DIR = os.path.join(HERE, "..", "models")

_missed = None
_delay = None

def load_models():
    global _missed, _delay
    if _missed is None:
        _missed = joblib.load(os.path.join(MODEL_DIR, "missed_boarding_model.pkl"))
    if _delay is None:
        _delay = joblib.load(os.path.join(MODEL_DIR, "flight_delay_model.pkl"))
    return _missed, _delay

# ----- prediction -----
MB_FEATURES = ["minutes_to_departure", "checked_in_at_gate", "zone_distance_min",
               "prior_late_count", "is_frequent_flyer"]
DL_FEATURES = ["dep_hour", "carrier_idx", "weather_bad", "inbound_late", "is_weekend"]

def predict_missed_boarding(p):
    model, _ = load_models()
    X = pd.DataFrame([[p[f] for f in MB_FEATURES]], columns=MB_FEATURES)
    prob = float(model.predict_proba(X)[0][1])
    band = "HIGH" if prob >= 0.6 else "MEDIUM" if prob >= 0.35 else "LOW"
    return {"risk": round(prob, 3), "band": band}

def predict_delay(f):
    _, model = load_models()
    X = pd.DataFrame([[f[k] for k in DL_FEATURES]], columns=DL_FEATURES)
    prob = float(model.predict_proba(X)[0][1])
    return {"delay_prob": round(prob, 3), "likely_delayed": prob >= 0.5}

